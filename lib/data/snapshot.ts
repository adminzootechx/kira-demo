import "server-only";

import { readFileSync, statSync } from "node:fs";
import { join } from "node:path";

import { autoMapColumns, buildRecords, parseCsv } from "./csv";
import { buildCustomerProfiles } from "@/lib/analytics/customer";
// MODEL_VERSION is imported for its value, not its type, so a snapshot can
// never report a model version the scoring code is not actually running.
import { MODEL_VERSION, type ActiveBook } from "@/lib/db/repository";
import type { Dimensions } from "@/lib/db/dimensions";

/**
 * The demo dataset, for running without a database.
 *
 * The files are generated by `scripts/generate-demo-data.mjs` from the same
 * simulated sales, so they agree with each other. Every name in them is
 * fictional.
 *
 *   - `demo-dimensions.json` has the shape `getDimensions()` returns.
 *   - `demo-orders.json` is each customer's order history.
 *   - `demo-customers.csv` is the customer grain as facts, parsed here by the
 *     same `parseCsv`/`buildRecords` an upload goes through and scored by the
 *     same `buildCustomerProfiles` the database path uses.
 *
 * A live database always wins — this is only consulted when there is no
 * active import to read.
 */

const DIR = join(process.cwd(), "data");
const CUSTOMERS_FILE = join(DIR, "demo-customers.csv");
const DIMENSIONS_FILE = join(DIR, "demo-dimensions.json");

let dimensionsCache: Dimensions | null | undefined;

export function snapshotDimensions(): Dimensions | null {
  if (dimensionsCache !== undefined) return dimensionsCache;
  const raw = read(DIMENSIONS_FILE);
  dimensionsCache = raw ? (JSON.parse(raw) as Dimensions) : null;
  return dimensionsCache;
}
/** Read once per process; the file cannot change under a running deployment. */
let bookCache: ActiveBook | null | undefined;

function read(file: string): string | null {
  try {
    return readFileSync(file, "utf8");
  } catch {
    // A missing snapshot is not an error. It means this checkout has none, and
    // the caller falls back to the sample book exactly as it would with a
    // database that is simply empty.
    return null;
  }
}


export function snapshotBook(): ActiveBook | null {
  if (bookCache !== undefined) return bookCache;

  const raw = read(CUSTOMERS_FILE);
  if (!raw) {
    bookCache = null;
    return bookCache;
  }

  const rows = parseCsv(raw);
  const mapping = autoMapColumns(rows[0] ?? []);
  const { records } = buildRecords(rows, mapping);
  if (!records.length) {
    bookCache = null;
    return bookCache;
  }

  let generatedAt = new Date(0).toISOString();
  try {
    generatedAt = statSync(CUSTOMERS_FILE).mtime.toISOString();
  } catch {
    // Keep the epoch default; the date is informational on `/data`.
  }

  bookCache = {
    customers: buildCustomerProfiles(records),
    meta: {
      // There is no import row behind a snapshot. Zero is not a real id and no
      // route looks one up — `/customers/[id]` keys off the customer slug.
      importId: 0,
      fileName: "Demo sales data (sample)",
      source: "snapshot",
      importedAt: generatedAt,
      rowCount: records.length,
      assumedFields: ["Payment score", "Estimated buying capacity"],
      modelVersion: MODEL_VERSION,
      dataAsOf: null,
    },
  };
  return bookCache;
}

export type SnapshotOrder = {
  orderNo: string; date: string; stones: number; carats: number; amount: number;
  discount: number; location: string; terms: string; owner: string;
  /** [shape, colour, clarity, lab, stones, carats, amount, discount, daysInStock, location] */
  lines: [string, string, string, string, number, number, number, number, number, string][];
};

let ordersCache: Record<string, SnapshotOrder[]> | null | undefined;

/** One customer's demo order history, newest first, by `clientKey`. */
export function snapshotOrders(key: string): SnapshotOrder[] {
  if (ordersCache === undefined) {
    const raw = read(join(DIR, "demo-orders.json"));
    ordersCache = raw ? (JSON.parse(raw) as Record<string, SnapshotOrder[]>) : null;
  }
  return ordersCache?.[key] ?? [];
}
